// Rebuild the marine recording repairs from the checked-in field takes.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { stationaryTexture } from './recording-texture.mjs';

const clips = new URL('../recipes/_recordings/', import.meta.url);

function rebuildWake(clip) {
  const pcm = Buffer.from(clip.takes[0], 'base64');
  const frame = seconds => Math.round(seconds * clip.sampleRate);
  const start = frame(2.26), begin = frame(.29), limit = frame(1.99), fade = frame(.072);
  const frames = pcm.length / 2, period = limit - begin - fade;
  if (limit >= start || start + fade >= frames) throw Error('Outboard cut requires a fresh source review');
  const result = Buffer.from(pcm);
  const sample = index => pcm.readInt16LE(2 * index);
  for (let i = start; i < frames; i++) {
    const offset = (i - start) % period;
    let replacement = sample(begin + fade + offset);
    if (offset >= period - fade) {
      const position = offset - period + fade;
      const angle = Math.PI * .5 * position / fade;
      replacement = replacement * Math.cos(angle) + sample(begin + position) * Math.sin(angle);
    }
    const gain = .5 - .5 * Math.cos(Math.PI * Math.min(1, (i - start) / fade));
    const mixed = sample(i) * (1 - gain) + replacement * gain;
    result.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(mixed))), 2 * i);
  }
  return result;
}

function rebuildCabin(clip) {
  // Preserve cabin coloration and broad changes in swell. Randomized spectral phase
  // removes the full sequence of sharp knocks that reads as typing in a quiet mix.
  const pcm = Buffer.from(clip.takes[0], 'base64');
  const frames = pcm.length / 2;
  const fftLength = 2 ** Math.ceil(Math.log2(frames));
  const bed = Buffer.from(stationaryTexture(clip.takes[0], clip.sampleRate, fftLength), 'base64');
  const result = Buffer.alloc(pcm.length);
  const radius = Math.round(.65 * clip.sampleRate);
  const energy = new Float64Array(frames + 1);
  for (let i = 0; i < frames; i++) energy[i + 1] = energy[i] + pcm.readInt16LE(i * 2) ** 2;
  const rms = Math.sqrt(energy[frames] / frames);
  for (let i = 0; i < frames; i++) {
    const left = Math.max(0, i - radius), right = Math.min(frames, i + radius + 1);
    const swell = Math.sqrt((energy[right] - energy[left]) / (right - left)) / rms;
    const gain = .55 + .35 * Math.min(1.25, swell);
    result.writeInt16LE(Math.round(bed.readInt16LE(i * 2) * gain), i * 2);
  }
  return result;
}

const repairs = [
  ['motion-outboard-aeration', '82b98873e2e7bc9857b3cf9010ac8c10d58db87b8a6e6e635efa2816d4743a7b', rebuildWake],
  ['motion-sailboat-cabin', '101d8147bbb0225d56bb40d00c25deebb2e4c4e744ee1fc8d8be2e904b7c2b25', rebuildCabin],
];
for (const [name, expected, repair] of repairs) {
  const { default: original } = await import(new URL(name + '.ts', clips));
  const actual = createHash('sha256').update(Buffer.from(original.takes[0], 'base64')).digest('hex');
  if (original.takes.length !== 1 || actual !== expected) throw Error('Review revised source takes for ' + name);
  const packed = { ...original, takes: [repair(original).toString('base64')] };
  const text = "// Generated by scripts/build-reviewed-takes.mjs\nimport type { RecordedClip } from '../../engine/recording.ts';\nexport default " +
    JSON.stringify(packed, null, 2) + ' satisfies RecordedClip;\n';
  const target = new URL('reviewed-' + name + '.ts', clips);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== text) throw Error('Review edit mismatch: ' + name);
  } else await writeFile(target, text);
}
